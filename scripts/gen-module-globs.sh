#!/usr/bin/env bash
# ci-gates-local: text-scan (the --check mode reads files only; other modes build)
# This package's two libraries name their modules one by one instead of globbing
# `CatCrypt.*`: Lake resolves an import to the first package in its
# (topologically sorted, dependencies first) workspace whose library glob matches
# the NAME, without looking at the file system. A `.submodules `CatCrypt` glob
# here would claim every `CatCrypt.*` module of a package that requires this one
# (the dev tree shares the namespace), and their builds would look for those
# files here. With an explicit list, a module this package does not name is left
# to the requiring package.
#
# The modules are split between three libraries:
#   CatCryptCompiler          the library (default target)
#   CatCryptCompilerExamples  demos, probes, tests and benchmark drivers
#   CatCryptCompilerVeir      the VeIR bridge (opt-in: `lake build CatCryptCompilerVeir`)
# The VeIR bridge is every module that imports `Veir.*`, every module whose name
# matches VEIR_RE, and, transitively, every module that imports one of these. The
# importers go with it because Lake builds an import whatever library names it:
# a default-target module importing a bridge module would put the bridge back in
# the default build. The bridge has no consumer in the compiler pipeline; it is
# kept buildable by its own target and checked by `lake build CatCryptCompilerVeir`.
# A module is an example when its path matches EXAMPLE_RE or it is listed in
# EXAMPLE_EXTRA, unless a library module imports it, directly or through other
# examples: the library never depends on the examples library, so such a module
# stays in the library. Module names are the same in both libraries; only the
# library membership differs, and a requiring package resolves a module of
# either library the same way.
#
# This script rewrites the generated block in lakefile.lean from `git ls-files`.
#   scripts/gen-module-globs.sh          rewrite the block
#   scripts/gen-module-globs.sh --check  exit 1 if the block is stale (CI)
#   scripts/gen-module-globs.sh --kept   list the example-shaped modules that
#                                        stay in the library, with an importer
#   scripts/gen-module-globs.sh --veir   list the modules of the opt-in VeIR
#                                        bridge library (read by the rot guard)
# A module added to this tree and not listed here builds with
# "no such file … catcrypt-compiler/…": regenerate.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
LF=lakefile.lean
BEGIN='-- BEGIN package modules (generated by scripts/gen-module-globs.sh; do not edit)'
END='-- END package modules'
EXAMPLE_RE='^CatCrypt\.Crypto\.SecureCompilation\.Ascent\.Demos\.|^CatCrypt\.Crypto\.Jasmin\.Examples\.|(Demo|Probe|Test|Tests|Bench[A-Za-z0-9]*)$'
EXAMPLE_EXTRA='CatCrypt.Hax.ReifyImpEndToEnd CatCrypt.Hax.ReifyImpDecodeEndToEnd'
VEIR_RE='^CatCrypt\.Crypto\.SecureCompilation\.(VIR\.(ComToVeir[A-Za-z0-9_]*|MlirScfDialect)|MLIRBackend\.ComToVeir)$'
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# The module set is every `.lean` under `CatCrypt/` that the index or `HEAD`
# names and that exists on disk. The index alone is not enough: this worktree
# is shared, and a concurrent session's staged deletion of a file it has not
# removed drops that module from the list, so the generated lakefile stops
# naming a module the committed tree carries and `--check` fails on the next
# push. `HEAD` alone is not enough either: a module added and not yet
# committed has to be listed before it can build. The disk test keeps a
# removed module out.
{ { git ls-files 'CatCrypt/*.lean' 'CatCrypt/**/*.lean'
    git ls-tree -r --name-only HEAD -- CatCrypt 2>/dev/null | grep -E '\.lean$' || true
  } | LC_ALL=C sort -u | while IFS= read -r f; do [ -f "$f" ] && printf '%s\n' "$f"; done \
    | sed 's#\.lean$##; s#/#.#g'; } | LC_ALL=C sort -u > "$work/all"

# Import edges "module dependency" between modules of the set. An import line
# inside a docstring can add a spurious edge; that only keeps a module in the
# library, never moves one out.
while IFS= read -r m; do
  grep -hoE '^(public[[:space:]]+)?(meta[[:space:]]+)?import([[:space:]]+all)?[[:space:]]+CatCrypt[A-Za-z0-9_.]*' \
      "$(printf '%s' "$m" | tr '.' '/').lean" 2>/dev/null \
    | sed -E "s/^.*[[:space:]]//; s/^/$m /" || true
done < "$work/all" > "$work/edges"

# The opt-in VeIR bridge: the seeds (a `Veir.*` import, or a name matching
# VEIR_RE) and every module that imports a module of the set, until none is left.
# The rest of this script works on the modules outside it.
{ grep -E "$VEIR_RE" "$work/all" || true
  while IFS= read -r m; do
    grep -qE '^(public[[:space:]]+)?(meta[[:space:]]+)?import([[:space:]]+all)?[[:space:]]+Veir(\.|[[:space:]]|$)' \
        "$(printf '%s' "$m" | tr '.' '/').lean" 2>/dev/null && printf '%s\n' "$m" || true
  done < "$work/all"
} | LC_ALL=C sort -u > "$work/veir"
while :; do
  awk 'NR==FNR { v[$1] = 1; next } ($2 in v) && !($1 in v) { print $1 }' "$work/veir" "$work/edges" \
    | LC_ALL=C sort -u > "$work/veir.add"
  [ -s "$work/veir.add" ] || break
  LC_ALL=C sort -u "$work/veir" "$work/veir.add" -o "$work/veir"
done
if [ "${1:-}" = "--veir" ]; then
  cat "$work/veir"
  exit 0
fi
LC_ALL=C comm -23 "$work/all" "$work/veir" > "$work/all.rest"
mv "$work/all.rest" "$work/all"

{ grep -E "$EXAMPLE_RE" "$work/all" || true
  printf '%s\n' $EXAMPLE_EXTRA | LC_ALL=C sort -u | LC_ALL=C comm -12 - "$work/all"
} | LC_ALL=C sort -u > "$work/examples"

# Move to the library every example a library module imports, until none is left.
: > "$work/kept"
while :; do
  LC_ALL=C comm -23 "$work/all" "$work/examples" > "$work/lib"
  awk 'NR==FNR { lib[$1] = 1; next } ($1 in lib) { print $2 }' "$work/lib" "$work/edges" \
    | LC_ALL=C sort -u | LC_ALL=C comm -12 - "$work/examples" > "$work/moved"
  [ -s "$work/moved" ] || break
  cat "$work/moved" >> "$work/kept"
  LC_ALL=C comm -23 "$work/examples" "$work/moved" > "$work/examples.new"
  mv "$work/examples.new" "$work/examples"
done

if [ "${1:-}" = "--kept" ]; then
  LC_ALL=C sort -u "$work/kept" | while IFS= read -r k; do
    printf '%s  <-  %s\n' "$k" "$(awk -v k="$k" 'NR==FNR { lib[$1] = 1; next }
      ($2 == k && ($1 in lib)) { print $1; exit }' "$work/lib" "$work/edges")"
  done
  exit 0
fi

# Chunks of 200: one array literal of every module exceeds the elaborator's
# recursion depth; the chunks are appended in the `globs` field.
chunks() {  # $1 = file of module names, $2 = def-name prefix
  awk -v p="$2" 'NR%200==1 { if (NR>1) print "  ]"; k++; printf "def %s%d : Array Lake.Glob := #[\n", p, k }
         { printf "    Lake.Glob.one `%s,\n", $0 }
         END { print "  ]"; print "" }' "$1"
}
globs_of() {  # $1 = file of module names, $2 = def-name prefix
  awk -v p="$2" 'END { k = int((NR + 199) / 200); s = ""
    for (i = 1; i <= k; i++) s = s (i > 1 ? " ++" : "") " " p i
    printf "  globs :=%s\n", s }' "$1"
}

tmp="$work/block"
{
  echo "$BEGIN"
  chunks "$work/lib" pkgModules
  chunks "$work/examples" exampleModules
  chunks "$work/veir" veirModules
  printf '@[default_target]\nlean_lib CatCryptCompiler where\n'
  globs_of "$work/lib" pkgModules
  printf '\n-- Demos, probes, tests and benchmark drivers. Nothing in `CatCryptCompiler`\n'
  printf -- '-- imports a module of this library.\n'
  printf 'lean_lib CatCryptCompilerExamples where\n'
  globs_of "$work/examples" exampleModules
  printf '\n-- The VeIR bridge, opt-in: `lake build CatCryptCompilerVeir`. Nothing in the\n'
  printf -- '-- other two libraries imports a module of this library.\n'
  printf 'lean_lib CatCryptCompilerVeir where\n'
  globs_of "$work/veir" veirModules
  echo "$END"
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  cur="$work/cur"
  awk -v b="$BEGIN" -v e="$END" '$0==b{p=1} p{print} $0==e{p=0}' "$LF" > "$cur"
  if cmp -s "$tmp" "$cur"; then
    echo "module list: fresh ($(wc -l < "$work/lib") library, $(wc -l < "$work/examples") example, $(wc -l < "$work/veir") VeIR bridge modules)"
    exit 0
  fi
  echo "STALE: the module lists in lakefile.lean differ from git ls-files; run scripts/gen-module-globs.sh" >&2
  diff "$cur" "$tmp" | head -10 >&2 || true
  exit 1
fi
if grep -qF -e "$BEGIN" "$LF"; then
  awk -v b="$BEGIN" -v e="$END" -v f="$tmp" '
    $0==b { while ((getline line < f) > 0) print line; skip=1; next }
    $0==e { skip=0; next }
    !skip { print }' "$LF" > "$LF.new" && mv "$LF.new" "$LF"
else
  echo "no generated block in $LF; insert the markers first" >&2; exit 2
fi
echo "module lists rewritten: $(wc -l < "$work/lib") library, $(wc -l < "$work/examples") example, $(wc -l < "$work/veir") VeIR bridge modules"
