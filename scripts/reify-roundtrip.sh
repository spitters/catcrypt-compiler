#!/bin/bash
# Reads the printed Rust text of a reifyImp% pilot back through the hax frontend.
#
# Usage (from any directory):
#   scripts/reify-roundtrip.sh FN DEF OUT
#     FN   the Rust function name of a pilot in CatCrypt.Hax.ReifyImp.pilots
#     DEF  the name of the generated Lean definition
#     OUT  the generated Lean module, relative to this repository's root
#
# Lake runs from the build root CATCRYPT_DEV_ROOT when that directory exists (a
# workspace whose root package depends on this one), and from this repository's
# root otherwise; the files the script reads and writes are in this repository.
#
# Pilots:
#   scripts/reify-roundtrip.sh edwards_add edwardsAddExtracted \
#     CatCrypt/Hax/ReifyImpPilotExtracted.lean
#   scripts/reify-roundtrip.sh decode decodeExtracted \
#     CatCrypt/Hax/ReifyImpDecodeExtracted.lean
#
# Steps:
#   1. the reify-emit executable (CatCrypt.Hax.ReifyImpEmit) writes, for every pilot,
#      bench/reify_roundtrip/FN.rs, the text ppImpRustFnRet prints for the literal,
#      and bench/reify_roundtrip/FN_leaves.rs, the leaf stubs leafStubsText renders
#      from the pilot's leaf list;
#   2. writes bench/reify_roundtrip/crate/src/lib.rs: the crate attributes,
#      FN_leaves.rs, then FN.rs;
#   3. `cargo hax json` on the crate writes hax_frontend_export.json;
#   4. bench/reify_roundtrip/read_back.lean reads the body of FN with hax-lean's
#      JSON adapter and writes it as the Lean literal DEF to OUT.
# The static check is the theorem that the reading is the literal (for the
# pilots, CatCrypt.Hax.ReifyImpEndToEnd and CatCrypt.Hax.ReifyImpDecodeEndToEnd);
# build it after this script.

set -euo pipefail

if [ "$#" -ne 3 ]; then
  sed -n '4,8p' "$0" >&2
  exit 2
fi

# a large hax export overflows the default stack of the JSON reader
ulimit -s unlimited 2>/dev/null || true

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEV="${CATCRYPT_DEV_ROOT:-$ROOT/../SSProve-lean}"
[ -d "$DEV" ] || DEV="$ROOT"
BENCH="$ROOT/bench/reify_roundtrip"
CRATE="$BENCH/crate"
FN="$1"
DEF="$2"
OUT="$3"

cd "$DEV"
lake build catcryptCompiler/reify-emit >/dev/null
"$ROOT/.lake/build/bin/reify-emit" "$BENCH"

for f in "$BENCH/$FN.rs" "$BENCH/${FN}_leaves.rs"; do
  if [ ! -f "$f" ]; then
    echo "reify-emit wrote no $f: is $FN a pilot?" >&2
    exit 1
  fi
done

mkdir -p "$CRATE/src"
{
  echo "//! Generated by scripts/reify-roundtrip.sh; do not edit."
  echo "#![allow(unused_mut, unused_variables, unused_assignments, dead_code, redundant_semicolons, unused_parens, non_snake_case)]"
  echo
  cat "$BENCH/${FN}_leaves.rs"
  echo
  cat "$BENCH/$FN.rs"
} > "$CRATE/src/lib.rs"

rm -f "$CRATE/hax_frontend_export.json"
(cd "$CRATE" && cargo hax json)

if [ ! -f "$CRATE/hax_frontend_export.json" ]; then
  echo "cargo hax json wrote no $CRATE/hax_frontend_export.json" >&2
  exit 1
fi

lake env lean --run "$ROOT/bench/reify_roundtrip/read_back.lean" \
  "$CRATE/hax_frontend_export.json" "$FN" "$DEF" "$ROOT/$OUT"
