#!/usr/bin/env python3
"""Write kat_table.h: the digests of the test message at the lengths of the harness.

The test message of length n has byte i = (31 i + 7) mod 256, as in the Rust tests of the
crates (sponge-hax, blake2b-hax, sha512-hax). Run: python3 gen_kat.py
"""
import hashlib

LENS = [0, 1, 64, 127, 128, 1000, 1024, 16384]
HASHES = [
    ("sha512", lambda m: hashlib.sha512(m).digest()),
    ("sha3_256", lambda m: hashlib.sha3_256(m).digest()),
    ("shake128_256", lambda m: hashlib.shake_128(m).digest(32)),
    ("shake256_512", lambda m: hashlib.shake_256(m).digest(64)),
    ("blake2b_512", lambda m: hashlib.blake2b(m).digest()),
]


def msg(n):
    return bytes(((i * 31 + 7) & 0xFF) for i in range(n))


def main():
    out = ["/* kat_table.h -- generated by gen_kat.py: the digests of the test message (byte i is",
           " * 31 i + 7 mod 256) at the lengths KAT_LENS, from Python hashlib. */",
           "#ifndef KAT_TABLE_H", "#define KAT_TABLE_H", "",
           "static const unsigned long KAT_LENS[8] = {%s};" % ", ".join(map(str, LENS)), ""]
    for name, f in HASHES:
        out.append("static const char *const KAT_%s[8] = {" % name.upper())
        for n in LENS:
            out.append('  "%s",' % f(msg(n)).hex())
        out.append("};")
        out.append("")
    out.append("#endif")
    with open("kat_table.h", "w") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
