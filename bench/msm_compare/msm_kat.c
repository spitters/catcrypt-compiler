/*
 * Known-answer test for the EMITTED MSM kernel (the pairing-ZK shared hot
 * computation: Sum_{i=0}^{L-1} k_i * P_i over an EC group).
 *
 * `ec_msm` is emitted from CatCrypt's verified front
 * (bench/msm_compare/msm_emit.lean, MsmEmit.msmJazz) as a REAL single-level
 * `for i = 0 to 8` loop whose body is the two EC leaves:
 *
 *     for i = 0 to 8 {
 *       psi = ec_scalar_mul(ks[i], ps[i]);   // the per-term op  k_i * P_i  (lane op)
 *       acc = ec_point_add(acc, psi);        // the accumulating op  +      (hsum op)
 *     }
 *
 * starting from acc = infinity (the EC AddCommMonoid 0).  This is the
 * `scalarFold` reduction over the EC group: the straight-line left-fold the
 * emitter produces equals the mathematical multi-scalar multiplication, proved
 * at the EC-group lane by MsmReduce.msm_eq_scalarFold (MsmEmit.msmKernel_dot).
 *
 * The leaves (ec_leaves.jinc) are table-driven schoolbook EC over Z/23 whose
 * tables are generated by gen_tables.c from THIS reference's group law.  The
 * reference oracle here is the INDEPENDENT ec_msm_ref (ec_ref.h): schoolbook
 * double-and-add scalar-mul + schoolbook affine point-add, no dlog tables.  The
 * emitted-and-leaf-linked ec_msm must agree byte-for-byte with ec_msm_ref on
 * every input -- discharging MsmReduce.EcLeafAgrees operationally.
 *
 * No fabricated vectors: every expected answer is computed by ec_msm_ref.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "ec_ref.h"

#define L 8   /* must match MsmEmit.L and the emitted ABI u8[8] / u8[16] */

/* OWNED x86-64 kernel (bench/msm_compare/msm_owned_emit.lean, no jasminc),
 * front-sourced to the WORD ABI (output path gen_com/msm.s):
 *   out = Sum_i ks[i] * (ps[2i], ps[2i+1]) over the curve, in dlog space.
 * SysV ABI (the TRUE emitted order, read off gen_com/msm.s -- NOT the emit
 * docstring, which listed the last two args swapped):
 *   ec_msm(out, ks, ps, DLOG, zero, POW) in rdi/rsi/rdx/rcx/r8/r9.
 * The register->role reading from the .s: RDI = out (store base), RSI = ks
 * (fold load, index 0..7), RDX = ps (index 0..15), RCX = DLOG (index up to
 * 6120), R8 = zero (the .reg 64 accumulator seed slot), R9 = POW (epilogue
 * load base). Passing POW in R8 and zero in R9 (the old order) faults: the
 * epilogue POW gather reads base R9, so POW must land in R9.
 * returns the out pointer in rax (we ignore the return). EVERY buffer is a
 * uint64_t word array (one word per scalar / coordinate / table entry / output
 * byte), the front's memref model -- NOT the old byte ABI.
 *   ks[i]      = scalar (byte-valued, in a u64 word)
 *   ps[2i]/ps[2i+1] = x_i / y_i in Z/23 (infinity = 0xff/0xff)
 *   DLOG[23*x+y]    = dlog of (x,y); 0 for infinity and any out-of-curve index
 *                     (the table absorbs infinity -- NO in-kernel branch, so the
 *                     default is 0, not the old 255 sentinel).
 *   zero            = a zeroed word seeding the accumulator.
 *   POW[m]          = x_m | (y_m << 8) for m = 0..27 (POW[0] = 0xffff = infinity)
 *   out[0]/out[1]   = low byte holds x / y of the result point. */
extern uint64_t *ec_msm(uint64_t out[2], const uint64_t ks[L], const uint64_t ps[2 * L],
                        const uint64_t *DLOG, uint64_t zero, const uint64_t *POW);

#define EC_ORDER  28
/* DLOG is indexed 23*x+y over byte-valued coords: infinity (0xff,0xff) lands at
 * 23*255+255 = 6120, so the table must span 6121 words (matches
 * MsmZ23Owned.Ldlog). Every unfilled slot -- infinity and out-of-curve -- is 0. */
#define EC_DLOG_N 6121
/* The two leaf tables, built once from ec_ref.h's OWN group law (the same trust
 * model as the previous jasminc gen_tables.c route); the comparison oracle
 * ec_msm_ref (schoolbook double-and-add) stays table-free and independent. */
static uint64_t EC_DLOG_T[EC_DLOG_N];
static uint64_t EC_POW_T[EC_ORDER];

static void build_tables(void) {
  ec_point pow_pts[EC_ORDER];
  ec_point G = { 0, 1 };
  ec_point Racc = ec_inf();
  pow_pts[0] = Racc;
  for (int j = 1; j < EC_ORDER; j++) { Racc = ec_point_add_ref(Racc, G); pow_pts[j] = Racc; }
  for (int i = 0; i < EC_DLOG_N; i++) EC_DLOG_T[i] = 0;   /* infinity / off-curve -> 0 */
  for (int j = 1; j < EC_ORDER; j++)
    EC_DLOG_T[23 * pow_pts[j].x + pow_pts[j].y] = (uint64_t)j;
  for (int m = 0; m < EC_ORDER; m++)
    EC_POW_T[m] = (uint64_t)pow_pts[m].x | ((uint64_t)pow_pts[m].y << 8);
}

/* j*G as a wire point, via the reference scalar-mul on G = (0,1). */
static ec_point ref_mult(int j) {
  ec_point G = { 0, 1 };
  return ec_scalar_mul_ref((uint8_t)j, G);
}

/* Run one case: fill ks/ps, compare emitted ec_msm against ec_msm_ref. The
 * emit takes the WORD ABI, so widen the byte test vectors into u64 word arrays
 * and read the low byte of each output word; the reference oracle stays on bytes. */
static int run_case(const char *label, const uint8_t ks[L], const uint8_t ps[2 * L]) {
  uint64_t ksw[L], psw[2 * L], outw[2];
  for (int i = 0; i < L; i++)     ksw[i] = (uint64_t)ks[i];
  for (int i = 0; i < 2 * L; i++) psw[i] = (uint64_t)ps[i];
  ec_msm(outw, ksw, psw, EC_DLOG_T, 0, EC_POW_T);
  uint8_t got[2] = { (uint8_t)outw[0], (uint8_t)outw[1] };
  uint8_t ref[2];
  ec_msm_ref(ks, ps, L, ref);
  if (got[0] != ref[0] || got[1] != ref[1]) {
    printf("FAIL [%s]: emitted=(%u,%u) ref=(%u,%u)\n",
           label, got[0], got[1], ref[0], ref[1]);
    return 1;
  }
  printf("ok:   [%s] -> (%u,%u)\n", label, got[0], got[1]);
  return 0;
}

int main(void) {
  int fail = 0;
  build_tables();

  /* Case 1: all terms the point at infinity -> result infinity (fold of 0s). */
  {
    uint8_t ks[L], ps[2 * L];
    for (int i = 0; i < L; i++) { ks[i] = (uint8_t)(i + 1); ps[2*i] = EC_INF; ps[2*i+1] = EC_INF; }
    fail |= run_case("all-infinity terms", ks, ps);
  }

  /* Case 2: each P_i = G, scalars 1..L -> result = (1+2+...+L)*G = 36*G. */
  {
    uint8_t ks[L], ps[2 * L];
    ec_point G = { 0, 1 };
    for (int i = 0; i < L; i++) { ks[i] = (uint8_t)(i + 1); ps[2*i] = G.x; ps[2*i+1] = G.y; }
    fail |= run_case("P_i=G, k_i=1..8 (=36*G)", ks, ps);
  }

  /* Case 3: P_i = (i+1)*G, k_i = 1 -> result = sum_i (i+1)*G = 36*G (same value,
     reached by adding distinct points rather than scaling one). */
  {
    uint8_t ks[L], ps[2 * L];
    for (int i = 0; i < L; i++) {
      ec_point Pi = ref_mult(i + 1);
      ks[i] = 1; ps[2*i] = Pi.x; ps[2*i+1] = Pi.y;
    }
    fail |= run_case("P_i=(i+1)*G, k_i=1", ks, ps);
  }

  /* Case 4: P_i = 2*G for all i, alternating scalars -> exercises doubling base. */
  {
    uint8_t ks[L], ps[2 * L];
    ec_point H = ref_mult(2);
    uint8_t sc[L] = { 3, 5, 0, 7, 11, 1, 27, 2 };
    for (int i = 0; i < L; i++) { ks[i] = sc[i]; ps[2*i] = H.x; ps[2*i+1] = H.y; }
    fail |= run_case("P_i=2G, mixed scalars", ks, ps);
  }

  /* Case 5: deterministic pseudo-random scalars + points (an LCG seeded fixed),
     each point a curve point (i*G) so it is on-curve; the LCG produces no fake
     answers -- ec_msm_ref computes the expected value. */
  {
    uint8_t ks[L], ps[2 * L];
    uint32_t s = 0xC0FFEEu;
    for (int i = 0; i < L; i++) {
      s = s * 1103515245u + 12345u;
      ks[i] = (uint8_t)((s >> 16) & 0xff);            /* full byte scalar (reduced mod 28 inside) */
      int j = (int)((s >> 8) % 28u);                  /* 0..27 -> point j*G (incl. infinity at 0) */
      ec_point Pi = ref_mult(j);
      ps[2*i] = Pi.x; ps[2*i+1] = Pi.y;
    }
    fail |= run_case("pseudo-random scalars+points", ks, ps);
  }

  /* Case 6: a mix of infinity terms and finite terms (skip-on-infinity path). */
  {
    uint8_t ks[L], ps[2 * L];
    for (int i = 0; i < L; i++) {
      if (i % 2 == 0) { ps[2*i] = EC_INF; ps[2*i+1] = EC_INF; ks[i] = (uint8_t)(i + 1); }
      else { ec_point Pi = ref_mult(i + 1); ps[2*i] = Pi.x; ps[2*i+1] = Pi.y; ks[i] = (uint8_t)(2*i + 1); }
    }
    fail |= run_case("alternating infinity/finite", ks, ps);
  }

  /* Case 7: scalars that are multiples of the group order (28, 56, ...) -> each
     term is the identity, result infinity (exercises the m == 0 mod 28 path). */
  {
    uint8_t ks[L], ps[2 * L];
    uint8_t sc[L] = { 28, 56, 84, 0, 28, 0, 56, 0 };  /* all == 0 mod 28 */
    for (int i = 0; i < L; i++) {
      ec_point Pi = ref_mult((i % 5) + 1);
      ks[i] = sc[i]; ps[2*i] = Pi.x; ps[2*i+1] = Pi.y;
    }
    fail |= run_case("scalars =0 mod order -> infinity", ks, ps);
  }

  if (fail) { printf("KAT FAILED\n"); return 1; }
  printf("KAT PASSED (emitted ec_msm byte-identical to ec_msm_ref over %d cases)\n", 7);
  return 0;
}
